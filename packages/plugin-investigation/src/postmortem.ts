export interface PostmortemInput {
  incidentId: string;
  title: string;
  verdict: string;
  openedAt: Date;
  closedAt: Date;
  participants: Array<{ name: string; email: string }>;
  events: Array<{
    userName: string;
    toolName: string;
    summary?: string;
    cacheHit: boolean;
    createdAt: Date;
    inputArgs?: any;
    outputData?: any;
  }>;
}

export function generatePostmortemMarkdown(data: PostmortemInput): string {
  const durationMinutes = Math.max(1, Math.round((data.closedAt.getTime() - data.openedAt.getTime()) / (60 * 1000)));
  const totalQueries = data.events.length;
  const cachedQueries = data.events.filter(e => e.cacheHit || e.outputData?._cache?.hit).length;
  const cacheHitPercentage = totalQueries > 0 ? Math.round((cachedQueries / totalQueries) * 100) : 0;

  const timelineRows = data.events.length === 0
    ? '_No tool queries recorded in session._'
    : data.events.map(e => {
        const time = e.createdAt.toISOString().slice(11, 19);
        const cacheBadge = (e.cacheHit || e.outputData?._cache?.hit) ? ' `[CACHE HIT 0ms]`' : '';
        return `- **${time} UTC** [${e.userName}]: Executed \`${e.toolName}\`${cacheBadge} → ${e.summary || 'Completed query'}`;
      }).join('\n');

  return `
# Incident Postmortem: ${data.title}

| Field | Value |
|---|---|
| **Incident ID** | \`${data.incidentId}\` |
| **Duration (MTTR)** | ~${durationMinutes} minutes |
| **Opened At** | ${data.openedAt.toISOString()} |
| **Resolved At** | ${data.closedAt.toISOString()} |
| **Participants** | ${data.participants.map(p => `${p.name} (\`${p.email}\`)`).join(', ')} |
| **Resolution Verdict** | **${data.verdict}** |

---

## 1. Executive Summary
During this incident, on-call engineers identified and mitigated **${data.title}**. Total diagnostic queries executed across GCP, Sentry, and GitHub: **${totalQueries}** (with **${cacheHitPercentage}%** served instantly from the shared team cache).

---

## 2. Chronological Investigation Timeline
${timelineRows}

---

## 3. Evidence Locker & Root Cause Verification
- **Root Cause Determination:** ${data.verdict}
- **Primary Contributing Systems:** Google Cloud Platform, Sentry Error Tracking, GitHub Deployment Services.

---

## 4. Efficiency & FinOps Scorecard
- **Total Diagnostic Tool Calls:** ${totalQueries}
- **Redis Shared Cache Deduplication:** ${cachedQueries} calls saved (~${Math.round(cachedQueries * 0.05 * 100) / 100} USD API quota saved)
- **Investigation Artifact:** Living Postmortem auto-generated by Parallax.
`.trim();
}
